/* Generates src/theme-dark.css: the dark palette is the Tailwind colour scale remapped (CSS variables), so existing
 * utilities such as bg-zinc-50 / text-zinc-900 / border-zinc-200 / bg-red-50 get dark values without touching components.
 * Run: node scripts/theme/gen-dark.cjs  (output is committed; rerun only when changing the mapping). */
const fs = require('fs')
const path = require('path')
const theme = fs.readFileSync(path.join(__dirname, '../../node_modules/tailwindcss/theme.css'), 'utf8')
const vars = {}
for (const m of theme.matchAll(/--color-([a-z]+)-(\d+):\s*([^;]+);/g)) (vars[m[1]] ||= {})[m[2]] = m[3].trim()
const NEUTRAL = ['zinc', 'gray', 'slate', 'stone', 'neutral']
// neutral scales: page 50 -> 950, subtle fill 100 -> 800, border 200 -> 700, text 900 -> 50 ...
const NMAP = { 50: 950, 100: 800, 200: 700, 300: 600, 400: 500, 500: 400, 600: 300, 700: 200, 800: 100, 900: 50, 950: 50 }
// coloured scales: pale tints (50-300) become deep tints, dark text shades (700-900) become light; 400-500 stay (solid fills, white text)
const CMAP = { 50: 950, 100: 900, 200: 800, 300: 700, 700: 300, 800: 200, 900: 100, 950: 50 }
const dark = []
const orig = []
for (const [hue, shades] of Object.entries(vars)) {
  const map = NEUTRAL.includes(hue) ? NMAP : CMAP
  for (const [n, value] of Object.entries(shades)) {
    orig.push(`  --color-${hue}-${n}: ${value};`)
    if (map[n]) dark.push(`  --color-${hue}-${n}: ${shades[map[n]]};`)
    else if (!NEUTRAL.includes(hue) && n === '600') dark.push(`  --color-${hue}-600: color-mix(in oklab, ${value} 82%, white);`)
    else if (!NEUTRAL.includes(hue) && n === '500') dark.push(`  --color-${hue}-500: color-mix(in oklab, ${value} 90%, white);`)
  }
}
const css = `/* GENERATED by scripts/theme/gen-dark.cjs - do not edit by hand. See docs/infrastructure.md "Dark mode". */
@media screen {
  html.dark {
    color-scheme: dark;
    --color-background: #09090b;
    --color-foreground: #fafafa;
    --surface: #18181b;
${dark.join('\n').replace(/^/gm, '  ')}
  }
}

/* Areas that must keep the light look in dark mode (sidebar, print previews, signature, QR labels): add class "theme-light". */
.theme-light {
  color-scheme: light;
  --surface: #ffffff;
${orig.join('\n')}
}
`
fs.writeFileSync(path.join(__dirname, '../../src/theme-dark.css'), css)
console.log('written', css.length)
